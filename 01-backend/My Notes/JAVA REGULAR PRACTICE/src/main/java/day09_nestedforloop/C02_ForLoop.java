package day09_nestedforloop;

public class C02_ForLoop {

    public static void main(String[] args) {

        //1'den 100'e kadar hic rakam  kullanmadan sayilari konsola yazdiriniz
        //Hic rakam kullanmamak icin bir cari kendisine bolunce 1 elde edip yapıyoruz
        // 100'e kadar derken de yine sayı kullanmamak icin 'd' ye kadar diyoruz cunku
        // 'd' nin ASCII degeri 100 :)

        for (int i = 'a' / 'a' ; i <= 'd' ; i++) {//a nin ASCII degeri = 97
            System.out.print(i+ " ");

        }
























    }




















}
