package day01_variables;

public class C02_Variables {

    public static void main(String[] args) {

        //1-Farkli 3 data turunde variale olusturun ve bunlari yazdirin
        
        String okulIsmi = "Techpro";
        System.out.println("okulIsmi = " + okulIsmi);

        char ilkHarf = 'K';
        System.out.println("ilkHarf = " + ilkHarf);

        int sayi1 = 20;
        System.out.println("sayi1 = " + sayi1);

        //2- Isim ve soyisim icin iki variable olusturun ve bunlari yazdirin
        //isminiz: Ahmet Can
        //soyisminiz: Ates
        
        String isim = "Ahmet Can";
        String soyIsim = "Ates";

        System.out.println("isim = " + isim);
        System.out.println("soyIsim = " + soyIsim);


    }


}
